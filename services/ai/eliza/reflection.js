/** Приводить слово до вигляду, за яким шукаємо у словнику. */
function normalize(word) {
  return word.toLowerCase().replace(APOSTROPHES, "'");
}

/**
 * Перевертає особу у фразі користувача.
 *
 * @param {string} text — фраза користувача
 * @returns {{text: string, verbReflected: boolean, pronounReflected: boolean, swaps: Array}}
 *   verbReflected показує, чи вдалося перевести дієслово. Якщо ні — рушій
 *   візьме шаблон відповіді, який цитує слова користувача замість того,
 *   щоб будувати з них речення (інакше вийде «ти люблю малювати»).
 */
export function reflect(text) {
  // Розбиваємо на слова і роздільники, зберігаючи розділові знаки.
  // Парні індекси — слова, непарні — роздільники.
  const parts = String(text).split(/([^\p{L}\p{M}'’`ʼ‘]+)/u);

  let verbReflected = false;
  let pronounReflected = false;
  const swaps = [];

  const result = parts.map((token, index) => {
    if (index % 2 === 1 || token === '') return token;

    const key = normalize(token);

    if (Object.prototype.hasOwnProperty.call(PRONOUNS, key)) {
      pronounReflected = true;
      swaps.push({ from: token, to: PRONOUNS[key], kind: 'займенник' });
      return PRONOUNS[key];
    }

    if (Object.prototype.hasOwnProperty.call(VERBS, key)) {
      verbReflected = true;
      swaps.push({ from: token, to: VERBS[key], kind: 'дієслово' });
      return VERBS[key];
    }

    return token;
  });

  return {
    text: result.join(''),
    verbReflected,
    pronounReflected,
    swaps
  };
}
